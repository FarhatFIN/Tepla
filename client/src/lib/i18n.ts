export function t(key: string, lang: string, params?: Record<string, string | number>): string {
  // Try exact language, then fallback to English
  let text = translations[lang]?.[key] || translations.en?.[key] || key;
  // Replace {param} placeholders
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

export function useT(lang: string) {
  return (key: string, params?: Record<string, string | number>) => t(key, lang, params);
}
